"""### Batters Ranking and Classification

First, I'll load the player performance data and focus on players who have batted. Then, I'll rank them by Average, Strike Rate, Innings, Centuries, and Fifties. Finally, I'll categorize them into 'Runs' classes.
"""

import pandas as pd

# Load the player performance matrix
performance_df = pd.read_csv('player_performance_matrix.csv').set_index('player')

# Filter for batters (players with at least one batting inning)
batters_df = performance_df[performance_df['innings'] >= 15].copy()

# Rank batters based on the specified parameters (higher is better for all)
batters_df['avg_rank'] = batters_df['average'].rank(ascending=False, method='min')
batters_df['sr_rank'] = batters_df['strike_rate'].rank(ascending=False, method='min')
batters_df['innings_rank'] = batters_df['innings'].rank(ascending=False, method='min')
batters_df['hundreds_rank'] = batters_df['hundreds'].rank(ascending=False, method='min')
batters_df['fifties_rank'] = batters_df['fifties'].rank(ascending=False, method='min')


# Define quantile boundaries for batting average
# Using 5 quantiles for 5 classes (0-20%, 20-40%, 40-60%, 60-80%, 80-100%)
# `pd.qcut` is perfect for this, but if there are too few unique values, `cut` with custom bins is better.
# Given a small dataset of 4 players, direct manual bins or checking unique counts is safer.
if batters_df['average'].nunique() < 5:
    # Fallback for very small number of unique averages
    # For this specific 4-player dataset, let's use equal counts for now.
    # For demonstration, assign based on sorted order.
    # Using index as the player identifier directly
    sorted_averages = batters_df['average'].sort_values().index.tolist()
    # Simple classification for 4 players, could be more sophisticated for larger sets
    batter_class_map = {
        sorted_averages[0]: 'Class 1',
        sorted_averages[1]: 'Class 2',
        sorted_averages[2]: 'Class 3',
        sorted_averages[3]: 'Class 4'
    }
    batters_df['Runs_Class'] = [batter_class_map.get(player_idx, 'N/A') + f' (Avg: {batters_df.loc[player_idx]["average"]:.2f})' for player_idx in batters_df.index]

else:
    # This block would be for a larger dataset where quantiles make more sense
    batters_df['Runs_Class'] = pd.qcut(
        batters_df['average'],
        q=5, # 5 classes
        labels=[
            'Class 1 (Avg: Bottom 20%)',
            'Class 2 (Avg: 20-40%)',
            'Class 3 (Avg: 40-60%)',
            'Class 4 (Avg: 60-80%)',
            'Class 5 (Avg: Top 20%)'
        ],
        duplicates='drop' # Handle cases where quantile bins might be identical
    ).astype(str) + ' (Avg: ' + batters_df['average'].round(2).astype(str) + ')' # Add actual average

print("Batters Ranking and Classification (Quantile-based):")
display(batters_df[['average', 'strike_rate', 'innings', 'hundreds', 'fifties',
                    'avg_rank', 'sr_rank', 'innings_rank', 'hundreds_rank', 'fifties_rank',
                    'Runs_Class']].sort_values(by='avg_rank').head(10))

"""### Bowlers Ranking and Classification

Next, I'll filter for players who have bowled, rank them by Innings Bowled, Overs Bowled, Bowling Average, and Bowling Strike Rate, and categorize them into 'Wickets' classes.
"""

import pandas as pd

# Load the player performance matrix
performance_df = pd.read_csv('player_performance_matrix.csv').set_index('player')

# Filter for bowlers (players with at least one bowling inning)
bowlers_df = performance_df[performance_df['bowl_innings'] >= 15].copy()

# Calculate wickets per match
bowlers_df['wickets_per_match'] = bowlers_df['wickets'] / bowlers_df['bowl_innings']

# Rank bowlers based on the specified parameters
# For economy, bowl_average, bowl_strike_rate, lower is better (ascending=True)
bowlers_df['bowl_innings_rank'] = bowlers_df['bowl_innings'].rank(ascending=False, method='min')
bowlers_df['overs_rank'] = bowlers_df['overs'].rank(ascending=False, method='min')
bowlers_df['bowl_avg_rank'] = bowlers_df['bowl_average'].rank(ascending=True, method='min')
bowlers_df['bowl_sr_rank'] = bowlers_df['bowl_strike_rate'].rank(ascending=True, method='min')


# Define quantile boundaries for wickets per match
# Using 4 quantiles for 4 classes (0-25%, 25-50%, 50-75%, 75-100%)
if bowlers_df['wickets_per_match'].nunique() < 4:
    # Fallback for very small number of unique wickets_per_match
    # For demonstration, assign based on sorted order for this 2-player dataset.
    # Using index as the player identifier directly
    sorted_wpm = bowlers_df['wickets_per_match'].sort_values().index.tolist()
    bowler_class_map = {
        sorted_wpm[0]: 'Class 1',
        sorted_wpm[1]: 'Class 2'
    }
    bowlers_df['Wickets_Class'] = [bowler_class_map.get(player_idx, 'N/A') + f' (WPM: {bowlers_df.loc[player_idx]["wickets_per_match"]:.2f})' for player_idx in bowlers_df.index]

else:
    bowlers_df['Wickets_Class'] = pd.qcut(
        bowlers_df['wickets_per_match'],
        q=4, # 4 classes
        labels=[
            'Class 1 (WPM: Bottom 25%)',
            'Class 2 (WPM: 25-50%)',
            'Class 3 (WPM: 50-75%)',
            'Class 4 (WPM: Top 25%)'
        ],
        duplicates='drop' # Handle cases where quantile bins might be identical
    ).astype(str) + ' (WPM: ' + bowlers_df['wickets_per_match'].round(2).astype(str) + ')' # Add actual WPM

print("Bowlers Ranking and Classification (Quantile-based):")
display(bowlers_df[['bowl_innings', 'overs', 'wickets', 'wickets_per_match', 'economy', 'bowl_average', 'bowl_strike_rate',
                     'bowl_innings_rank', 'overs_rank', 'bowl_avg_rank', 'bowl_sr_rank',
                     'Wickets_Class']].sort_values(by='bowl_avg_rank').head(10))



