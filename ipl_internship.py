"""
build_performance_matrix.py

Builds a batting + bowling performance matrix for the players who played
every IPL season from 2008 to 2025 (output of find_players_2008_2025.py),
then ranks them using a composite z-score across chosen metrics.

Input : players_2008_to_2025_records.csv
Output: player_performance_matrix.csv   (raw + per-metric stats)
        player_ranking.csv              (z-scores + composite rank)
"""

import numpy as np
import pandas as pd

INPUT_FILE = "players_2008_to_2025_records.csv"
PLAYER_LIST_FILE = "players_2008_to_2025_list.csv"
OUTPUT_MATRIX = "player_performance_matrix.csv"
OUTPUT_RANKING = "player_ranking.csv"


def batting_stats(df, player):
    bat = df[df["batter"] == player]
    if bat.empty:
        return {
            "innings": 0, "runs": 0, "balls_faced": 0, "dismissals": 0,
            "not_outs": 0, "average": 0.0, "strike_rate": 0.0,
            "fours": 0, "sixes": 0, "fifties": 0, "hundreds": 0,
        }

    # Final runs/balls per innings = max cumulative value per match
    per_innings = bat.groupby("match_id").agg(
        final_runs=("batter_runs", "max"),
        final_balls=("batter_balls", "max"),
    )

    innings = len(per_innings)
    runs = per_innings["final_runs"].sum()
    balls_faced = per_innings["final_balls"].sum()

    # Dismissals: rows where this player is recorded as the one out
    dismissals = df[df["player_out"] == player]["match_id"].nunique()
    not_outs = innings - dismissals

    average = runs / dismissals if dismissals > 0 else runs  # all-not-out edge case
    strike_rate = (runs / balls_faced * 100) if balls_faced > 0 else 0.0

    fours = (bat["runs_batter"] == 4).sum()
    sixes = (bat["runs_batter"] == 6).sum()
    fifties = ((per_innings["final_runs"] >= 50) & (per_innings["final_runs"] < 100)).sum()
    hundreds = (per_innings["final_runs"] >= 100).sum()

    return {
        "innings": innings, "runs": int(runs), "balls_faced": int(balls_faced),
        "dismissals": int(dismissals), "not_outs": int(not_outs),
        "average": round(average, 2), "strike_rate": round(strike_rate, 2),
        "fours": int(fours), "sixes": int(sixes),
        "fifties": int(fifties), "hundreds": int(hundreds),
    }


def bowling_stats(df, player):
    bowl = df[df["bowler"] == player]
    if bowl.empty:
        return {
            "bowl_innings": 0, "balls_bowled": 0, "overs": 0.0,
            "runs_conceded": 0, "wickets": 0, "economy": 0.0,
            "bowl_average": 0.0, "bowl_strike_rate": 0.0,
        }

    per_innings_runs = bowl.groupby("match_id")["runs_bowler"].max()
    bowl_innings = len(per_innings_runs)
    runs_conceded = per_innings_runs.sum()

    balls_bowled = (bowl["valid_ball"] == 1).sum()
    overs = balls_bowled / 6
    wickets = bowl["bowler_wicket"].sum()

    economy = (runs_conceded / overs) if overs > 0 else 0.0
    bowl_average = (runs_conceded / wickets) if wickets > 0 else 0.0
    bowl_strike_rate = (balls_bowled / wickets) if wickets > 0 else 0.0

    return {
        "bowl_innings": int(bowl_innings), "balls_bowled": int(balls_bowled),
        "overs": round(overs, 1), "runs_conceded": int(runs_conceded),
        "wickets": int(wickets), "economy": round(economy, 2),
        "bowl_average": round(bowl_average, 2),
        "bowl_strike_rate": round(bowl_strike_rate, 2),
    }


def main():
    print(f"Reading {INPUT_FILE} ...")
    df = pd.read_csv(INPUT_FILE, low_memory=False)

    # IMPORTANT: players_2008_to_2025_records.csv contains full rows for any
    # delivery involving a qualifying player as batter/bowler/non-striker.
    # That means opposing bowlers/batters on those deliveries also appear as
    # values in the batter/bowler columns. We must NOT compute stats for
    # every name in the file -- only for the actual qualifying players.
    qualifying = pd.read_csv(PLAYER_LIST_FILE)["player"].tolist()
    players = sorted(qualifying)

    rows = []
    for p in players:
        b = batting_stats(df, p)
        bw = bowling_stats(df, p)
        row = {"player": p, **b, **bw}
        rows.append(row)

    matrix = pd.DataFrame(rows).set_index("player")
    matrix.to_csv(OUTPUT_MATRIX)
    print(f"\nPerformance matrix saved to {OUTPUT_MATRIX}")
    print(matrix.to_string())

    # ---------- Composite ranking via z-scores ----------
    # Metrics where HIGHER is better
    positive_metrics = ["runs", "average", "strike_rate", "fours", "sixes",
                         "fifties", "hundreds", "wickets"]
    # Metrics where LOWER is better
    negative_metrics = ["economy", "bowl_average", "bowl_strike_rate"]

    z = pd.DataFrame(index=matrix.index)
    for m in positive_metrics:
        std = matrix[m].std()
        z[f"z_{m}"] = 0.0 if std == 0 else (matrix[m] - matrix[m].mean()) / std

    for m in negative_metrics:
        std = matrix[m].std()
        # invert sign since lower is better
        z[f"z_{m}"] = 0.0 if std == 0 else -(matrix[m] - matrix[m].mean()) / std

    # Weighted composite: batting-heavy weighting since all 4 are primarily
    # batters here; adjust weights as needed for your analysis
    weights = {
        "z_runs": 0.20, "z_average": 0.15, "z_strike_rate": 0.15,
        "z_fours": 0.05, "z_sixes": 0.05, "z_fifties": 0.10, "z_hundreds": 0.10,
        "z_wickets": 0.10, "z_economy": 0.05,
        "z_bowl_average": 0.025, "z_bowl_strike_rate": 0.025,
    }
    z["composite_score"] = sum(z[col] * w for col, w in weights.items())
    z["rank"] = z["composite_score"].rank(ascending=False).astype(int)
    z = z.sort_values("rank")

    z.to_csv(OUTPUT_RANKING)
    print(f"\nRanking (composite z-score) saved to {OUTPUT_RANKING}")
    print(z[["composite_score", "rank"]].to_string())


if __name__ == "__main__":
    main()

