import pandas as pd

OUTPUT_ALL_RECORDS = "players_2008_to_2025_records.csv"
OUTPUT_PLAYER_LIST = "players_2008_to_2025_list.csv"
START_YEAR = 2012
END_YEAR = 2025

def main():
    possible_input_files = ["/content/IPL.csv", "/content/ipl.csv"]
    df = None
    loaded_file = None

    for fname in possible_input_files:
        try:
            print(f"Attempting to read {fname} ...")
            # Added on_bad_lines='skip' to bypass broken lines and low_memory=False
            df = pd.read_csv(fname, on_bad_lines='skip', low_memory=False)
            loaded_file = fname
            break
        except FileNotFoundError:
            print(f"File not found: {fname}. Trying next option...")
            continue
        except Exception as e:
            print(f"An unexpected error occurred while reading {fname}: {e}")
            continue

    if df is None:
        raise FileNotFoundError(f"Could not load any valid dataset from: {possible_input_files}")

    print(f"Successfully read data from {loaded_file}.")

    required_years = set(range(START_YEAR, END_YEAR + 1))

    role_cols = ["batter", "bowler", "non_striker"]
    frames = []
    for col in role_cols:
        temp = df[[col, "year"]].rename(columns={col: "player"})
        frames.append(temp)

    appearances = pd.concat(frames, ignore_index=True).dropna(subset=["player"])
    years_by_player = appearances.drop_duplicates().groupby("player")["year"].apply(set)

    qualifying_players = sorted(
        player for player, years in years_by_player.items()
        if required_years.issubset(years)
    )

    print(f"Found {len(qualifying_players)} player(s) who played in every season from {START_YEAR} to {END_YEAR}:")
    for p in qualifying_players:
        print(f"  - {p}")

    pd.DataFrame({"player": qualifying_players}).to_csv(OUTPUT_PLAYER_LIST, index=False)
    print(f"\nSaved player list to {OUTPUT_PLAYER_LIST}")

    mask = (
        df["batter"].isin(qualifying_players)
        | df["bowler"].isin(qualifying_players)
        | df["non_striker"].isin(qualifying_players)
    )
    records = df[mask]
    records.to_csv(OUTPUT_ALL_RECORDS, index=False)
    print(f"Saved {len(records)} matching records to {OUTPUT_ALL_RECORDS}")

if __name__ == "__main__":
    main()

